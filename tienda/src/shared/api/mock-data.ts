export function getMockProductDetail(slug: string): ProductDetail | null {
  const base = mockProducts.find(
    (p) => p.slug === slug || p.sku.toLowerCase() === slug.toLowerCase() || String(p.product_id) === slug,
  );
  if (!base) return null;
  return {
    ...base,
    description: `${base.short_description ?? base.name} Producto disponible en PC TRONIC con respaldo y verificación directa en nuestro inventario.`,
    specs: {
      Código: base.sku,
      Categoría: base.category_name,
      Marca: base.brand ?? 'Original',
      Especificación: base.compatibility_or_model ?? 'Estándar',
      Garantía: 'Respaldo directo PC TRONIC',
    },
    variants: [],
    images: base.thumbnail_url
      ? [
          {
            product_image_id: 1,
            image_url: base.thumbnail_url,
            image_alt: base.name,
            display_order: 1,
            is_primary: true,
          },
        ]
      : [],
  };
}
